// Declare variables using var, let, and const.

// var declaration
var name = "Kajal";
console.log("Name:", name);

// let declaration
let age = 23;
console.log("Age:", age);

// const declaration
const country = "India";
console.log("Country:", country);

// Updating var and let values
name = "Priya";
age = 26;

console.log("Updated Name:", name);
console.log("Updated Age:", age);
